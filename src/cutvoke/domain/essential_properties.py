"""Bounded composition references and instance-only exposed parameter overrides."""
from __future__ import annotations

import copy
import re

from cutvoke.domain.compositing import number
from cutvoke.domain.keyframes import parameter_spec
from cutvoke.domain.rational import Rational


def find_clip(sequence, clip_id):
    return next((clip for track in sequence.tracks for clip in track.clips if clip.id == clip_id), None)


def control_spec(sequence, control):
    if not isinstance(control, dict) or set(control) - {"id", "label", "clipId", "param"}:
        raise ValueError("exposed control accepts id/label/clipId/param")
    if not re.fullmatch(r"[A-Za-z0-9_.-]{1,96}", str(control.get("id", ""))):
        raise ValueError("exposed control id must be 1..96 safe characters")
    if not isinstance(control.get("label", ""), str) or len(control.get("label", "")) > 128:
        raise ValueError("exposed control label must be at most 128 characters")
    clip = find_clip(sequence, control.get("clipId"))
    if clip is None:
        raise ValueError(f"exposed control target is missing: {control.get('clipId')}")
    param = control.get("param")
    if param == "content":
        effect = next((effect for effect in clip.effects if effect.get("effectId") == "cutvoke.text"), None)
        if effect is None:
            raise ValueError("content control requires a text clip")
        return {"type": "string", "maxLength": 20000, "value": effect.get("params", {}).get("content", "")}
    minimum, maximum, default = parameter_spec(clip, param)
    if param == "volume":
        default = float(clip.volume.to_fraction())
    elif param in {"x", "y", "opacity", "rotation", "scale"}:
        transform = clip.transform()
        default = transform["position"].get(param, 0) if param in {"x", "y"} else transform.get(param, default)
    elif str(param).startswith("effect:"):
        _, instance, key = param.split(":", 2)
        effect = next(effect for effect in clip.effects if effect.get("instanceId") == instance)
        default = effect.get("params", {}).get(key, default)
    return {"type": "number", "minimum": minimum, "maximum": maximum, "value": default}


def set_value(clip, param, value):
    if param == "volume":
        clip.volume = Rational.from_float(value)
    elif param == "content":
        next(effect for effect in clip.effects if effect.get("effectId") == "cutvoke.text").setdefault("params", {})["content"] = value
    elif param.startswith("effect:"):
        _, instance, key = param.split(":", 2)
        next(effect for effect in clip.effects if effect.get("instanceId") == instance).setdefault("params", {})[key] = value
    else:
        effect = next((effect for effect in clip.effects if effect.get("effectId") == "cutvoke.transform"), None)
        if effect is None:
            effect = {"effectId": "cutvoke.transform", "version": "1.0.0", "instanceId": "ep_" + clip.id, "params": {}}
            clip.effects.append(effect)
        params = effect.setdefault("params", {})
        if param in {"x", "y"}:
            params.setdefault("position", {})[param] = value
        else:
            params[param] = value
    # An explicit instance override replaces the exposed property's master
    # curve. Other properties and the editable master retain their animation.
    clip.keyframes.pop(param, None)
    clip.property_links.pop(param, None)
    # Render-only marker keeps an exposed X override from being regenerated by
    # the master's spatial path, while the other axis still follows that path.
    clip._essential_overrides = getattr(clip, '_essential_overrides', set()) | {param}


def apply_overrides(sequence, values):
    if not isinstance(values, dict) or len(values) > 128:
        raise ValueError("propertyOverrides must contain at most 128 controls")
    controls = {control["id"]: control for control in sequence.exposed_properties}
    for key, value in values.items():
        control = controls.get(key)
        if control is None:
            raise ValueError(f"unknown exposed property {key}")
        spec = control_spec(sequence, control)
        if spec["type"] == "string":
            if not isinstance(value, str) or len(value) > spec["maxLength"]:
                raise ValueError(f"{key} requires text with at most {spec['maxLength']} characters")
        else:
            number(value, key, spec["minimum"], spec["maximum"])
        set_value(find_clip(sequence, control["clipId"]), control["param"], value)


def validate(project):
    sequences = {sequence.id: sequence for sequence in project.sequences}
    if len(sequences) != len(project.sequences):
        raise ValueError("duplicate sequence IDs")
    count = [0]
    def walk(sequence, path=(), objects=()):
        count[0] += 1
        if count[0] > 2048 or len(path) > 16:
            raise ValueError("composition graph exceeds 16 levels or 2048 instances")
        if id(sequence) in objects:
            raise ValueError("composition dependency cycle")
        if len(sequence.exposed_properties) > 128:
            raise ValueError("at most 128 exposed properties per composition")
        ids = set()
        for control in sequence.exposed_properties:
            control_spec(sequence, control)
            if control["id"] in ids:
                raise ValueError("duplicate exposed property ID")
            ids.add(control["id"])
        for track in sequence.tracks:
            for clip in track.clips:
                child = clip.nested
                if clip.sequence_ref:
                    if child is not None:
                        raise ValueError("choose embedded nested or shared sequenceRef, not both")
                    if clip.sequence_ref not in sequences:
                        raise ValueError(f"missing composition {clip.sequence_ref}")
                    child = sequences[clip.sequence_ref]
                    if child.id in path or child is sequence:
                        raise ValueError(f"composition dependency cycle through {child.id}")
                if clip.property_overrides:
                    if child is None:
                        raise ValueError("property overrides require a composition instance")
                    apply_overrides(copy.deepcopy(child), clip.property_overrides)
                if child is not None:
                    walk(child, (*path, sequence.id), (*objects, id(sequence)))
    for sequence in project.sequences:
        walk(sequence)


def resolve(project):
    validate(project)
    if not any(clip.sequence_ref or clip.property_overrides for seq in project.sequences for track in seq.tracks for clip in track.clips):
        # Embedded nested overrides can appear deeper than one level.
        def needed(sequence):
            return any(c.sequence_ref or c.property_overrides or (c.nested is not None and needed(c.nested)) for t in sequence.tracks for c in t.clips)
        if not needed(project.sequence):
            return project
    snapshot = copy.deepcopy(project)
    sequences = {seq.id: seq for seq in snapshot.sequences}
    def walk(seq):
        for track in seq.tracks:
            for clip in track.clips:
                if clip.sequence_ref:
                    clip.nested = copy.deepcopy(sequences[clip.sequence_ref])
                    clip.sequence_ref = ""
                if clip.nested is not None:
                    if clip.property_overrides:
                        apply_overrides(clip.nested, clip.property_overrides)
                        clip.property_overrides = {}
                    walk(clip.nested)
    walk(snapshot.sequence)
    return snapshot


def at_path(project, path):
    """Read an authoring composition in local time without modifying its parent."""
    if not isinstance(path, list) or not 1 <= len(path) <= 16 or any(not isinstance(item, str) for item in path):
        raise ValueError("compositionPath requires 1..16 clip IDs")
    snapshot = copy.deepcopy(project)
    sequence = snapshot.sequence
    for clip_id in path:
        clip = find_clip(sequence, clip_id)
        if clip is None:
            raise ValueError(f"composition path clip missing: {clip_id}")
        sequence = clip.nested or next((item for item in snapshot.sequences if item.id == clip.sequence_ref), None)
        if sequence is None:
            raise ValueError(f"clip is not a composition: {clip_id}")
    snapshot.sequence = sequence
    snapshot.active_sequence_id = sequence.id
    if not any(item is sequence for item in snapshot.sequences):
        snapshot.sequences.append(sequence)
    return snapshot
